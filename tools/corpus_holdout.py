"""A held-out problem set, written after the compiler to estimate the hidden set.

The hidden evaluation set is "the same five categories, with different shapes,
sizes and op mixes, no surprise concepts", generated by the organisers' tool
from a private expression file. These specs imitate that file: the style of
``expressions_open.py``, new shapes (odd sizes, tall and wide rows, deep and
shallow contractions, other head sizes), and the open set's conventions:
reductions pinned to its schedule, exact pointwise ops checked with rtol = 0,
float64 references elsewhere. None of these expressions was used to develop or
tune the compiler.

    python tools/make_corpus.py --hackathon <emmy-hackathon-2026> --specs tools/corpus_holdout.py --out holdout
"""

import math

import numpy as np

REDUCE_KNOBS = "WORK=t128,REDUCE=coop"

f64 = np.float64
f32 = np.float32
_erf = np.vectorize(math.erf, otypes=[np.float64])


def _softmax(x, axis=-1):
    m = x.max(axis=axis, keepdims=True)
    e = np.exp(x - m)
    return e / e.sum(axis=axis, keepdims=True)


def _c(fn):
    """Reference computed in float64, rounded once to float32."""
    return lambda *a: [np.asarray(fn(*(x.astype(f64) for x in a))).astype(f32)]


def _e(fn):
    """Reference computed in float32 (exact IEEE ops, compare with rtol=0)."""
    return lambda *a: [np.asarray(fn(*a)).astype(f32)]


def pw(id, code, ref, rtol=1e-6, atol=1e-6):
    return dict(id=f"hp_{id}", code=code, ref=ref, rtol=rtol, atol=atol)


def red(id, code, ref, rtol=1e-4, atol=1e-4):
    return dict(id=f"hr_{id}", code=code, ref=ref, rtol=rtol, atol=atol, knobs=REDUCE_KNOBS)


def mm(id, m, k, n):
    return dict(id=f"hm_{id}", code=f"torch.randn({m}, {k}) @ torch.randn({k}, {n})",
                ref=_c(lambda a, b: a @ b), rtol=1e-3, atol=1e-3)


def fused(id, code, ref, rtol=1e-3, atol=1e-4):
    return dict(id=f"hf_{id}", code=code, ref=ref, rtol=rtol, atol=atol)


def attn(id, nq, nk, d, scale):
    code = (f"q = torch.randn({nq}, {d}); kt = torch.randn({d}, {nk}); v = torch.randn({nk}, {d}); "
            f"torch.softmax(q @ kt / {scale}, dim=-1) @ v")
    return dict(id=f"ha_{id}", code=code, ref=_c(lambda q, kt, v: _softmax((q @ kt) / scale) @ v),
                rtol=1e-3, atol=1e-4)


def sdpa(id, shape):
    b, h, n, d = shape
    t = f"torch.randn({b}, {h}, {n}, {d})"
    return dict(id=f"ha_{id}", code=f"q = {t}; k = {t}; v = {t}; torch.nn.functional.scaled_dot_product_attention(q, k, v)",
                ref=_c(lambda q, k, v: _softmax(q @ np.swapaxes(k, -1, -2) / np.sqrt(d)) @ v), rtol=1e-3, atol=1e-4)


